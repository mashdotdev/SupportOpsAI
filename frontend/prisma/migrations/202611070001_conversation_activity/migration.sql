CREATE TABLE public.agent_conversations (
    id UUID PRIMARY KEY,
    user_id TEXT NOT NULL,
    source TEXT NOT NULL CHECK (source IN ('test', 'live')),
    agent_id UUID,
    agent_name TEXT NOT NULL,
    agent_version INTEGER,
    model_id TEXT NOT NULL,
    subject TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress','answered','needs_clarification','needs_attention','resolved','inactive')),
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(id, user_id)
);
-- Historical agent identity deliberately survives agent deletion.
CREATE INDEX agent_conversations_owner_created_idx ON public.agent_conversations(user_id, source, created_at DESC);
CREATE INDEX agent_conversations_owner_updated_idx ON public.agent_conversations(user_id, updated_at DESC);
CREATE TABLE public.agent_turns (
    id UUID PRIMARY KEY,
    conversation_id UUID NOT NULL,
    user_id TEXT NOT NULL,
    question TEXT NOT NULL,
    answer TEXT,
    citations JSONB NOT NULL DEFAULT '[]',
    response_type TEXT,
    status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running','completed','failed','cancelled')),
    error TEXT,
    duration_ms INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    FOREIGN KEY(conversation_id, user_id) REFERENCES public.agent_conversations(id, user_id) ON DELETE CASCADE
);
CREATE INDEX agent_turns_conversation_created_idx ON public.agent_turns(conversation_id, created_at, id);
CREATE UNIQUE INDEX agent_turns_one_running_idx ON public.agent_turns(conversation_id) WHERE status='running';
CREATE TABLE public.agent_activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL,
    user_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY(conversation_id, user_id) REFERENCES public.agent_conversations(id, user_id) ON DELETE CASCADE
);
CREATE INDEX agent_activity_events_owner_id_idx ON public.agent_activity_events(user_id, id);
